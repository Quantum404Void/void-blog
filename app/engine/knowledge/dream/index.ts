export function dreamInterpret(keyword: string): SymbolMatrix {
  const matrix = createEmptyMatrix('dream', `梦境关键词: ${keyword}`)
  const matches: { kw: string; text: string }[] = []

  for (const [k, v] of Object.entries(DREAM_DICT)) {
    if (keyword.includes(k)) {
      matches.push({ kw: k, text: v })
    }
  }

  if (matches.length === 0) {
    matrix.interpretations.push({
      id: 'dream-none', ruleId: 'dream-none', category: 'general',
      text: `未找到与"${keyword}"相关的梦境解释。尝试输入其他关键词（如水、火、蛇、鱼、龙、虎、飞、落等）。`,
      tone: 'neutral', weight: 50
    })
    return matrix
  }

  for (const m of matches) {
    matrix.symbols.push({ id: `dream-${m.kw}`, name: m.kw, category: 'dream', position: '梦境', attributes: { keyword: m.kw } })
    matrix.interpretations.push({
      id: `dream-${m.kw}`, ruleId: 'dream-dict', category: 'general',
      text: `梦${m.kw}：${m.text}`,
      tone: 'neutral', source: '《周公解梦》', weight: 70
    })
  }

  return matrix
}
